/**
 * Pure SVG renderers for every kuraykaraaslan labs brand asset. Each function returns a
 * string and touches nothing else, so `build.mjs` can write them and
 * `brand.test.mjs` can compare the committed files against them.
 */
import {
  ARMS,
  BRANCHES,
  COLORS,
  FONT_STACK,
  FORK,
  MONO_STACK,
  SITE,
  NODE_RADIUS,
  NODE_SHIFT,
  STEM,
  STROKE_WIDTH,
  TAGLINE,
  TILE_RADIUS,
  VIEW_BOX,
  WORDMARK,
  WORDMARK_ADVANCE,
  WORDMARK_X,
} from "./geometry.mjs";

export const LABEL = `${WORDMARK.name}${WORDMARK.accent}`;

/** The two wordmark spans, on one line: under xml:space="preserve" a newline
 *  inside the <text> renders as a leading space. */
function spans(p) {
  return `<tspan fill="${p.text}">${WORDMARK.name}</tspan><tspan fill="${p.toneOne}">${WORDMARK.accent}</tspan>`;
}
const GENERATED = "GENERATED by brand/build.mjs from brand/geometry.mjs. Do not hand-edit.";

function palette(inverse) {
  return inverse
    ? {
        toneOne: COLORS.toneOneInverse,
        toneTwo: COLORS.toneTwoInverse,
        tile: COLORS.tile,
        ground: COLORS.tileInverse,
        text: COLORS.foregroundInverse,
        muted: COLORS.foregroundMutedInverse,
        grid: COLORS.gridLineInverse,
      }
    : {
        toneOne: COLORS.toneOne,
        toneTwo: COLORS.toneTwo,
        tile: COLORS.tile,
        ground: COLORS.paper,
        text: COLORS.foreground,
        muted: COLORS.foregroundMuted,
        grid: COLORS.gridLine,
      };
}

/** The house mark: tile, stem and both arms in the trunk blue, a live node
 *  on each arm tip. The tile is always the dark ground, on either surface,
 *  so the mark itself never changes between light and dark. */
export function houseMark({ radius = TILE_RADIUS } = {}) {
  const { toneOne, toneTwo, tile } = palette(false);
  const arm = (tip) =>
    `<path d="M${FORK.x} ${FORK.y} L${tip.x} ${tip.y}" stroke="${toneOne}" stroke-width="${STROKE_WIDTH}" stroke-linecap="round" fill="none"/>`;
  return [
    `<rect width="64" height="64" rx="${radius}" fill="${tile}"/>`,
    `<rect x="${STEM.x}" y="${STEM.y}" width="${STEM.width}" height="${STEM.height}" rx="${STEM.radius}" fill="${toneOne}"/>`,
    ...ARMS.map(arm),
    ...ARMS.map((tip) => `<circle cx="${tip.x}" cy="${tip.y}" r="${NODE_RADIUS}" fill="${toneTwo}"/>`),
  ].join("\n  ");
}

/** A kui-* package mark: the same construction without nodes, so it sits at
 *  the family's own coordinates; the lower arm carries the package tone. */
export function familyMark(toneTwo) {
  const s = (x) => x - NODE_SHIFT;
  return [
    `<rect width="64" height="64" rx="${TILE_RADIUS}" fill="${COLORS.tile}"/>`,
    `<rect x="${s(STEM.x)}" y="${STEM.y}" width="${STEM.width}" height="${STEM.height}" rx="${STEM.radius}" fill="${COLORS.toneOne}"/>`,
    `<path d="M${s(FORK.x)} ${FORK.y} L${s(ARMS[0].x)} ${ARMS[0].y}" stroke="${COLORS.toneOne}" stroke-width="${STROKE_WIDTH}" stroke-linecap="round" fill="none"/>`,
    `<path d="M${s(FORK.x)} ${FORK.y} L${s(ARMS[1].x)} ${ARMS[1].y}" stroke="${toneTwo}" stroke-width="${STROKE_WIDTH}" stroke-linecap="round" fill="none"/>`,
  ].join("\n  ");
}

export function markSvg({ square = false } = {}) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEW_BOX}" width="64" height="64" role="img" aria-label="${LABEL} mark">
  <title>${LABEL} mark</title>
  <!-- ${GENERATED} -->
  ${houseMark({ radius: square ? 0 : TILE_RADIUS })}
</svg>
`;
}

export function familyMarkSvg({ id, toneTwo }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEW_BOX}" width="64" height="64" role="img" aria-label="${id} mark">
  <title>${id} mark</title>
  <!-- ${GENERATED} -->
  ${familyMark(toneTwo)}
</svg>
`;
}

/** Derived from the label, never fixed — a hard-coded box clips the moment
 *  the fallback font is wider than the one it was sized for. */
const LOCKUP_WIDTH = Math.ceil(WORDMARK_X + LABEL.length * WORDMARK_ADVANCE + 16);

/** Mark + wordmark. The gap equals the clear space: half the mark's height. */
export function wordmarkSvg({ inverse = false } = {}) {
  const p = palette(inverse);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${LOCKUP_WIDTH} 64" width="${LOCKUP_WIDTH}" height="64" role="img" aria-label="${LABEL}">
  <title>${LABEL}</title>
  <!-- ${GENERATED} -->
  ${houseMark()}
  <text x="${WORDMARK_X}" y="41" font-family="${FONT_STACK}" font-size="26" font-weight="600" letter-spacing="-0.5" xml:space="preserve">${spans(p)}</text>
</svg>
`;
}

/**
 * The brand motif: the mark's own construction laid on its side. A trunk,
 * and one 45-degree branch per shipped product, alternating up and down,
 * each ending in a live node with the product's name.
 */
function branchGraph({ x0, y, spacing, reach, stroke, node, fontSize, p }) {
  const parts = [];
  const lastFork = x0 + (BRANCHES.length - 1) * spacing;
  parts.push(
    `<path d="M${x0 - spacing / 2} ${y} L${lastFork + spacing / 2} ${y}" stroke="${p.toneOne}" stroke-width="${stroke}" stroke-linecap="round" fill="none"/>`,
  );
  BRANCHES.forEach((name, i) => {
    const fx = x0 + i * spacing;
    const up = i % 2 === 0;
    const tx = fx + reach;
    const ty = up ? y - reach : y + reach;
    const labelY = up ? ty - node - fontSize * 0.6 : ty + node + fontSize * 1.3;
    parts.push(
      `<path d="M${fx} ${y} L${tx} ${ty}" stroke="${p.toneOne}" stroke-width="${stroke}" stroke-linecap="round" fill="none"/>`,
      `<circle cx="${tx}" cy="${ty}" r="${node}" fill="${p.toneTwo}"/>`,
      `<text x="${tx}" y="${labelY}" text-anchor="middle" font-family="${MONO_STACK}" font-size="${fontSize}" fill="${p.muted}">${name}</text>`,
    );
  });
  return parts.join("\n  ");
}

function backdrop(width, height, p, id) {
  return [
    `<defs>`,
    `  <pattern id="${id}" width="32" height="32" patternUnits="userSpaceOnUse">`,
    `    <path d="M32 0 L0 0 0 32" fill="none" stroke="${p.grid}" stroke-width="1"/>`,
    `  </pattern>`,
    `</defs>`,
    `<rect width="${width}" height="${height}" fill="${p.ground}"/>`,
    `<rect width="${width}" height="${height}" fill="url(#${id})" opacity="0.7"/>`,
  ].join("\n  ");
}

/** 1280x440 header for the organization profile; one file per theme.
 *  Stacked, not side by side: the name is too long to share a row with the
 *  graph, so the graph runs the full width underneath it. */
export function bannerSvg({ inverse = false } = {}) {
  const p = palette(inverse);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 440" width="1280" height="440" role="img" aria-label="${LABEL} — ${TAGLINE}">
  <title>${LABEL} — ${TAGLINE}</title>
  <!-- ${GENERATED} -->
  ${backdrop(1280, 440, p, "grid")}
  <g transform="translate(72 56) scale(2)">
  ${houseMark()}
  </g>
  <text x="232" y="126" font-family="${FONT_STACK}" font-size="56" font-weight="600" letter-spacing="-1.5" xml:space="preserve">${spans(p)}</text>
  <text x="234" y="168" font-family="${FONT_STACK}" font-size="24" fill="${p.muted}">${TAGLINE}</text>
  ${branchGraph({ x0: 136, y: 320, spacing: 144, reach: 52, stroke: 6, node: 8, fontSize: 18, p })}
</svg>
`;
}

/** 1280x640 — GitHub's social preview size; rasterised by build.mjs. */
export function socialSvg() {
  const p = palette(true);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 640" width="1280" height="640" role="img" aria-label="${LABEL} — ${TAGLINE}">
  <title>${LABEL} — ${TAGLINE}</title>
  <!-- ${GENERATED} -->
  ${backdrop(1280, 640, p, "grid")}
  <g transform="translate(96 88) scale(2)">
  ${houseMark()}
  </g>
  <text x="1184" y="160" text-anchor="end" font-family="${MONO_STACK}" font-size="22" fill="${p.muted}">${SITE}</text>
  <text x="96" y="318" font-family="${FONT_STACK}" font-size="76" font-weight="600" letter-spacing="-2" xml:space="preserve">${spans(p)}</text>
  <text x="98" y="370" font-family="${FONT_STACK}" font-size="30" fill="${p.text}">${TAGLINE}</text>
  ${branchGraph({ x0: 136, y: 500, spacing: 144, reach: 52, stroke: 6, node: 8, fontSize: 19, p })}
</svg>
`;
}
